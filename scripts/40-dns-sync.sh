#!/usr/bin/env bash
# Publishes the DNS records Stalwart generates (DKIM keys, DMARC, MX, SRV,
# MTA-STS, TLSA) in the lab zone, next to the static A records.
# Re-run after adding a domain or replacing the TLS certificate.
set -euo pipefail
cd "$(dirname "$0")/.."

ZONE=dns/zones/lab.internal.zone
cp dns/zones/static.zone "$ZONE"

# Collected before the loop: the CLI runs in a container and would otherwise
# consume the rest of this list from stdin.
DOMAINS=$(./scripts/sw.sh query Domain --json --fields id,name 2>/dev/null | python3 -c '
import sys, json
for line in sys.stdin:
    line = line.strip()
    if line.startswith("{"):
        o = json.loads(line)
        print(o["id"], o["name"])
')

while read -r id name; do
	[ -n "$id" ] || continue
	{
		echo
		echo "; ---- ${name} (generated by Stalwart) ----"
	} >> "$ZONE"
	# </dev/null: the CLI container would otherwise eat the rest of the list.
	./scripts/sw.sh get Domain "$id" --json 2>/dev/null </dev/null \
		| python3 -c 'import sys, json; print(json.load(sys.stdin).get("dnsZoneFile", ""))' \
		>> "$ZONE"
done <<< "$DOMAINS"

# The file plugin only polls for changes once a minute, so restart instead of
# waiting for it.
docker compose restart dns >/dev/null
sleep 3

echo "==> records now served:"
dig +short -p 15353 @127.0.0.1 MX  lab.internal        | sed 's/^/    MX  lab.internal: /'
dig +short -p 15353 @127.0.0.1 MX  other.lab.internal  | sed 's/^/    MX  other.lab.internal: /'
dig +short -p 15353 @127.0.0.1 TXT _dmarc.lab.internal | sed 's/^/    TXT _dmarc.lab.internal: /'
dig +short -p 15353 @127.0.0.1 A   mail.lab.internal   | sed 's/^/    A   mail.lab.internal: /'
